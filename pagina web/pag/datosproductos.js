function cargarProductos() {
    const contenedor = document.getElementById("contenedor-productos");
    if (!contenedor) return;


    contenedor.innerHTML = "";


    inventarioproducto.forEach((producto) => {

        const precioFormateado = producto.precio.toLocaleString("es-CL");

        const cardHTML = `
            <div class="col-sm-3 col-md-3">
                <div class="card h-100 shadow-sm">
                    <img src="${producto.imagen}" class="card-img-top p-2" alt="${producto.nombre}">
                    <div class="card-body d-flex flex-column justify-content-between p-2">
                        <div>
                            <h6 class="card-title text-truncate mb-1" title="${producto.nombre}">
                                ${producto.nombre}
                            </h6>
                            <p class="card-text text-muted small mb-1">${producto.autor}</p>
                            <p class="fw-bold text-primary mb-2">$${precioFormateado}</p>
                        </div>
                        <a href="producto.html?id=${producto.id}" class="btn btn-outline-dark btn-sm w-100">
                            Ver detalle
                        </a>
                    </div>
                </div>
            </div>
        `;

        contenedor.innerHTML += cardHTML;
    });
}


document.addEventListener("DOMContentLoaded", cargarProductos);